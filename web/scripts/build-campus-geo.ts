// Builds web/src/data/campusGeo.ts from the map's bundled demo day: a position for each place the
// web app knows, and the walking distance along the bundled OpenStreetMap pedestrian routes for
// each pair that has one. Run from the repo root after the map data changes:
//   node web/scripts/build-campus-geo.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface DemoDay {
  locations: { id: string; position: [number, number] }[];
  walkRoutes: Record<string, { cumulative: number[] }>;
  walkRouteSources: { retrieved: string; attribution: string };
}

const source = fileURLToPath(new URL('../../map-client/public/data/demo-day.json', import.meta.url));
const target = fileURLToPath(new URL('../src/data/campusGeo.ts', import.meta.url));
const day = JSON.parse(readFileSync(source, 'utf8')) as DemoDay;

const impact = JSON.parse(readFileSync(new URL('../../map-client/public/data/event-impact.json', import.meta.url), 'utf8')) as { places: { id: string }[] };
const ids = impact.places.map(location => location.id);
const positions: Record<string, [number, number]> = {};
for (const loc of day.locations) if (ids.includes(loc.id)) positions[loc.id] = loc.position;

const walkMeters: Record<string, number> = {};
for (let i = 0; i < ids.length; i++) {
  for (let j = i + 1; j < ids.length; j++) {
    const [a, b] = [ids[i], ids[j]].sort();
    const route = day.walkRoutes[`${a}>${b}`] ?? day.walkRoutes[`${b}>${a}`];
    if (route) walkMeters[`${a}>${b}`] = Math.round(route.cumulative[route.cumulative.length - 1]);
  }
}

const body = `// Generated by web/scripts/build-campus-geo.ts from map-client/public/data/demo-day.json. Do not edit.
// Walking routes: ${day.walkRouteSources.attribution}, retrieved ${day.walkRouteSources.retrieved}.

import type { CampusGeo } from './types';

export const campusGeo: CampusGeo = {
  positions: {
${Object.entries(positions).map(([id, p]) => `    ${JSON.stringify(id)}: [${p[0]}, ${p[1]}],`).join('\n')}
  },
  walkMeters: {
${Object.entries(walkMeters).map(([k, m]) => `    ${JSON.stringify(k)}: ${m},`).join('\n')}
  },
};
`;
writeFileSync(target, body);
console.log(`Wrote ${Object.keys(positions).length} positions and ${Object.keys(walkMeters).length} walking distances to ${target}`);
