// Builds web/src/data/campusStops.ts: for each MBTA and BU Shuttle map stop that the map's bundled
// demo day routes riders from, its name and the walking distance along the bundled OpenStreetMap
// pedestrian route to each nearby place (demo-day.json "stopRoutes", data-pipeline/make_demo_routes.py),
// plus the MBTA route names and direction names from transit.json.
// The departure planner walks to and from stops only along these routes; it never guesses one.
// Run from the repo root after the map data changes:
//   node web/scripts/build-campus-stops.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const data = (name: string) => JSON.parse(readFileSync(new URL(`../../map-client/public/data/${name}`, import.meta.url), 'utf8'));
const target = fileURLToPath(new URL('../src/data/campusStops.ts', import.meta.url));

const day = data('demo-day.json') as { stopRoutes: Record<string, { cumulative: number[] }>; walkRouteSources: { retrieved: string; attribution: string } };
const transit = data('transit.json') as { stops: { id: string; name: string }[]; routes: { id: string; name: string; longName?: string; kind: string; directions?: string[] }[] };
const shuttle = data('shuttle-schedule.json') as { stops: Record<string, { mapStopId: string | null; name?: string }> };

const names = new Map<string, string>(transit.stops.map((stop) => [stop.id, stop.name]));
// TransLoc's own stop ids (BU:2160…) carry the rider-facing names; the BU:addr:… copies come second.
for (const [id, stop] of Object.entries(shuttle.stops).sort(([a], [b]) => Number(a.includes('addr')) - Number(b.includes('addr')) || a.localeCompare(b))) {
  if (stop.mapStopId && stop.name && !names.has(stop.mapStopId)) names.set(stop.mapStopId, stop.name);
}

const stops: Record<string, { name: string; walkMeters: Record<string, number> }> = {};
for (const [key, route] of Object.entries(day.stopRoutes).sort(([a], [b]) => a.localeCompare(b))) {
  const [stop, place] = key.split('>');
  const name = names.get(stop);
  if (!name || !place) continue;
  (stops[stop] ??= { name, walkMeters: {} }).walkMeters[place] = Math.round(route.cumulative[route.cumulative.length - 1]);
}

const routes: Record<string, { name: string; directions: [string, string] | null }> = {};
for (const route of transit.routes) {
  routes[route.id] = {
    name: route.kind === 'subway' ? route.longName ?? route.name : `Bus ${route.name}`,
    directions: route.directions?.length === 2 ? [route.directions[0], route.directions[1]] : null,
  };
}

const body = `// Generated by web/scripts/build-campus-stops.ts from map-client/public/data/demo-day.json (stopRoutes),
// transit.json and shuttle-schedule.json (stop names). Do not edit.
// Walking routes: ${day.walkRouteSources.attribution}, retrieved ${day.walkRouteSources.retrieved}.

import type { CampusRoutes, CampusStops } from './types';

export const campusStops: CampusStops = ${JSON.stringify(stops, null, 2)};

export const campusRoutes: CampusRoutes = ${JSON.stringify(routes, null, 2)};
`;
writeFileSync(target, body);
console.log(`Wrote ${Object.keys(stops).length} stops with ${Object.values(stops).reduce((n, s) => n + Object.keys(s.walkMeters).length, 0)} walking routes to ${target}`);
